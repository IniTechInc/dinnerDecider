// Package auth is the service's authentication: a pairing token, the session
// cookies it can be exchanged for, the middleware that enforces them, and the
// startup guard that refuses an unauthenticated LAN bind.
//
// # Why there is no KDF here
//
// The pairing token is 32 bytes straight from crypto/rand, base32-encoded. It
// is a 256-bit random credential, not a password.
//
// bcrypt, scrypt and argon2 exist to make guessing expensive when the secret is
// low-entropy and human-chosen, because such a secret lives inside a dictionary
// an attacker can enumerate. There is no dictionary for 256 bits of
// crypto/rand: an attacker who can grab the hash file gains nothing from a slow
// hash, and an attacker who cannot is up against 2^256. A single SHA-256 is the
// right primitive, and it keeps the module free of golang.org/x/crypto — which
// matters here, because go.mod is frozen.
package auth

import (
	"crypto/rand"
	"crypto/sha256"
	"crypto/subtle"
	"encoding/base32"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"sync"
)

// TokenBytes is the entropy in a pairing token.
const TokenBytes = 32

// File names inside the auth directory.
const (
	// TokenHashFileName holds the credential of record. Verification reads only
	// this file.
	TokenHashFileName = "token.hash"
	// TokenFileName holds a local copy of the token itself, so that
	// `dinnerdecider token show` can print it after first start.
	//
	// The trade-off is deliberate and worth stating plainly: with this file
	// present, the SHA-256 in token.hash buys nothing against an attacker who
	// can already read the state directory. What it buys is that the token
	// never passes through the verification path in recoverable form, never
	// reaches a log, and does not travel in a backup that captured only the
	// hash. An operator who wants the stronger property can delete this file:
	// authentication keeps working, and `token show` then says the token is no
	// longer recoverable and offers to rotate it.
	TokenFileName = "token"
)

// Modes for everything this package writes.
const (
	FileMode os.FileMode = 0o600
	DirMode  os.FileMode = 0o700
)

// ErrTokenNotRecoverable is returned by Show when the hash exists but the local
// copy of the token does not. Authentication is unaffected; the token simply
// cannot be printed again and must be rotated.
var ErrTokenNotRecoverable = errors.New("auth: the token is no longer recoverable; rotate it to get a new one")

// tokenEncoding is unpadded base32. Uppercase letters and digits 2-7 only: no
// character pairs a human will confuse when reading a token off a terminal and
// typing it into a phone, and no padding characters to mangle in a URL.
var tokenEncoding = base32.StdEncoding.WithPadding(base32.NoPadding)

// GenerateToken returns a fresh pairing token.
func GenerateToken() (string, error) {
	buf := make([]byte, TokenBytes)
	if _, err := rand.Read(buf); err != nil {
		return "", fmt.Errorf("auth: generate token: %w", err)
	}
	return tokenEncoding.EncodeToString(buf), nil
}

// HashToken is the credential transform. One SHA-256 pass; see the package doc
// for why that is the whole story.
func HashToken(token string) [sha256.Size]byte {
	return sha256.Sum256([]byte(strings.TrimSpace(token)))
}

// TokenStore owns the token hash on disk and answers verification questions.
type TokenStore struct {
	dir string

	mu     sync.RWMutex
	hash   [sha256.Size]byte
	loaded bool
}

// NewTokenStore returns a store rooted at dir, normally $DD_STATE_DIR/auth.
func NewTokenStore(dir string) *TokenStore { return &TokenStore{dir: dir} }

// Dir is the directory this store uses.
func (s *TokenStore) Dir() string { return s.dir }

func (s *TokenStore) hashPath() string  { return filepath.Join(s.dir, TokenHashFileName) }
func (s *TokenStore) tokenPath() string { return filepath.Join(s.dir, TokenFileName) }

// Ensure loads the existing token hash, or creates a token when there is none.
//
// created reports that a token was generated by this call, in which case token
// carries it — that is the one moment it can be printed. On the load path token
// is empty even though Show can still recover it, so that a restart cannot
// re-print a credential into the journal.
func (s *TokenStore) Ensure() (token string, created bool, err error) {
	if err := s.prepareDir(); err != nil {
		return "", false, err
	}

	if data, err := os.ReadFile(s.hashPath()); err == nil {
		h, perr := parseHash(data)
		if perr == nil {
			s.mu.Lock()
			s.hash, s.loaded = h, true
			s.mu.Unlock()
			return "", false, nil
		}
		return "", false, fmt.Errorf("auth: %s is unreadable (%w); delete it to have a new token generated", s.hashPath(), perr)
	} else if !errors.Is(err, os.ErrNotExist) {
		return "", false, fmt.Errorf("auth: read %s: %w", s.hashPath(), err)
	}

	tok, err := s.write()
	if err != nil {
		return "", false, err
	}
	return tok, true, nil
}

// Rotate replaces the token unconditionally and returns the new one. Every
// existing pairing token stops working immediately; sessions already issued are
// unaffected until they expire, which is the caller's business.
func (s *TokenStore) Rotate() (string, error) {
	if err := s.prepareDir(); err != nil {
		return "", err
	}
	return s.write()
}

func (s *TokenStore) write() (string, error) {
	tok, err := GenerateToken()
	if err != nil {
		return "", err
	}
	h := HashToken(tok)
	if err := writeSecret(s.hashPath(), []byte(hex.EncodeToString(h[:])+"\n")); err != nil {
		return "", err
	}
	if err := writeSecret(s.tokenPath(), []byte(tok+"\n")); err != nil {
		return "", err
	}
	s.mu.Lock()
	s.hash, s.loaded = h, true
	s.mu.Unlock()
	return tok, nil
}

// Show returns the token for the `token show` subcommand.
//
// It re-derives the hash from the local copy and checks it against the
// credential of record, because printing a token that would not actually work —
// after a hand edit, a partial restore, or a rotation that half-completed — is
// worse than admitting it cannot be recovered.
func (s *TokenStore) Show() (string, error) {
	data, err := os.ReadFile(s.tokenPath())
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return "", ErrTokenNotRecoverable
		}
		return "", fmt.Errorf("auth: read %s: %w", s.tokenPath(), err)
	}
	tok := strings.TrimSpace(string(data))
	if tok == "" {
		return "", ErrTokenNotRecoverable
	}

	stored, err := os.ReadFile(s.hashPath())
	if err != nil {
		return "", fmt.Errorf("auth: read %s: %w", s.hashPath(), err)
	}
	want, err := parseHash(stored)
	if err != nil {
		return "", fmt.Errorf("auth: %s is unreadable: %w", s.hashPath(), err)
	}
	got := HashToken(tok)
	if subtle.ConstantTimeCompare(got[:], want[:]) != 1 {
		return "", fmt.Errorf("auth: the stored token does not match %s; rotate it: %w", TokenHashFileName, ErrTokenNotRecoverable)
	}
	return tok, nil
}

// Forget removes the local copy of the token, leaving authentication working
// but making the token unrecoverable. Exposed so an operator can harden an
// install without reaching into the state directory by hand.
func (s *TokenStore) Forget() error {
	if err := os.Remove(s.tokenPath()); err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("auth: remove %s: %w", s.tokenPath(), err)
	}
	return nil
}

// Verify reports whether presented is the pairing token.
//
// The comparison is crypto/subtle.ConstantTimeCompare over the hashes. Both
// sides are fixed-length SHA-256 output, so an attacker learns nothing from how
// long the answer took — and the length of the presented string, which is not
// secret, is the only thing that varies the work.
func (s *TokenStore) Verify(presented string) bool {
	s.mu.RLock()
	stored, loaded := s.hash, s.loaded
	s.mu.RUnlock()
	if !loaded {
		return false
	}
	got := HashToken(presented)
	return subtle.ConstantTimeCompare(got[:], stored[:]) == 1
}

// Loaded reports whether a token hash is in memory. False before Ensure.
func (s *TokenStore) Loaded() bool {
	s.mu.RLock()
	defer s.mu.RUnlock()
	return s.loaded
}

func (s *TokenStore) prepareDir() error {
	if s.dir == "" {
		return errors.New("auth: token store needs a directory")
	}
	if err := os.MkdirAll(s.dir, DirMode); err != nil {
		return fmt.Errorf("auth: create %s: %w", s.dir, err)
	}
	// MkdirAll honours the umask and leaves an existing directory's mode alone.
	if err := os.Chmod(s.dir, DirMode); err != nil {
		return fmt.Errorf("auth: chmod %s: %w", s.dir, err)
	}
	return nil
}

func parseHash(data []byte) ([sha256.Size]byte, error) {
	var out [sha256.Size]byte
	raw, err := hex.DecodeString(strings.TrimSpace(string(data)))
	if err != nil {
		return out, fmt.Errorf("not hex: %w", err)
	}
	if len(raw) != sha256.Size {
		return out, fmt.Errorf("expected %d bytes of SHA-256, got %d", sha256.Size, len(raw))
	}
	copy(out[:], raw)
	return out, nil
}

// writeSecret writes owner-only and re-asserts the mode, so a file left loose
// by a restore or an earlier version is corrected rather than inherited.
func writeSecret(path string, data []byte) error {
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_TRUNC, FileMode)
	if err != nil {
		return fmt.Errorf("auth: write %s: %w", path, err)
	}
	if _, err := f.Write(data); err != nil {
		f.Close()
		return fmt.Errorf("auth: write %s: %w", path, err)
	}
	if err := f.Close(); err != nil {
		return fmt.Errorf("auth: write %s: %w", path, err)
	}
	if err := os.Chmod(path, FileMode); err != nil {
		return fmt.Errorf("auth: chmod %s: %w", path, err)
	}
	return nil
}
